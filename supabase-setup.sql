-- Run in your own Supabase project: SQL Editor > New query > Run.
-- Guests may ONLY INSERT. No public SELECT/UPDATE/DELETE.
create table if not exists public.wedding_rsvps (
  id bigint generated always as identity primary key,
  guest_name text not null check (char_length(trim(guest_name)) between 1 and 100),
  attendance text not null check (attendance in ('yes', 'no')),
  guest_count smallint not null check (guest_count between 0 and 5),
  message text not null default '' check (char_length(message) <= 500),
  created_at timestamptz not null default now(),
  constraint valid_guest_count check (
    (attendance = 'no' and guest_count = 0) or
    (attendance = 'yes' and guest_count between 1 and 5)
  )
);

alter table public.wedding_rsvps enable row level security;
-- Explicit grants are required for newly created Supabase projects.
revoke all on table public.wedding_rsvps from anon, authenticated;
grant usage on schema public to anon;
grant insert (guest_name, attendance, guest_count, message)
  on table public.wedding_rsvps to anon;
-- Do not grant SELECT, UPDATE, or DELETE to anon.
-- Identity generated by default (no sequence grant needed for inserts).

drop policy if exists "Wedding guests can respond" on public.wedding_rsvps;
create policy "Wedding guests can respond"
  on public.wedding_rsvps
  for insert to anon
  with check (true);
